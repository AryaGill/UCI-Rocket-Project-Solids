// Microsecond resolution time
void DWT_Init(void)
{
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk; // Enable DWT
    DWT->CYCCNT = 0;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;            // Start counter
}

uint32_t micros(void)
{
    return DWT->CYCCNT / (SystemCoreClock / 1000000);
}

// Success: 3 quick LED blinks + 2 distinct buzzer tones
void Success_Pattern(void)
{
    // 3 quick LED blinks
	for(int i = 0; i < 3; i++) {
	        HAL_GPIO_WritePin(LED_GPIO_Port, LED_Pin, GPIO_PIN_SET);
	        HAL_Delay(150);  // Slightly longer ON
	        HAL_GPIO_WritePin(LED_GPIO_Port, LED_Pin, GPIO_PIN_RESET);
	        HAL_Delay(150);
	    }

    HAL_Delay(1000); //  pause

    // 2 distinct quick beeps
    for(int i = 0; i < 2; i++) {
    	__HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, htim4.Init.Period / 2);
		HAL_Delay(150);
		__HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, 0);
        HAL_Delay(150);
    }

    // Turn buzzer ON and keep it on
    __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, htim4.Init.Period / 2);
}

// Error: Rapid LED flashing + continuous buzzer beeps, system halts
void Error_Pattern(void)
{
    while(1) {
        // Rapid LED flashing (50ms on/off)
        HAL_GPIO_WritePin(LED_GPIO_Port, LED_Pin, GPIO_PIN_SET);
        HAL_Delay(50);
        HAL_GPIO_WritePin(LED_GPIO_Port, LED_Pin, GPIO_PIN_RESET);
        HAL_Delay(50);

        // Continuous beeping via PWM: 200ms tone, 200ms silence
        // Tone ON
        __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, htim4.Init.Period / 2); // 50% duty
        HAL_Delay(200);

        // Tone OFF (duty = 0)
        __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, 0);
        HAL_Delay(200);
    }
    // System halts here - never returns
}

